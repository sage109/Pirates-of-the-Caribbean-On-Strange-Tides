def t(key: str, language: str = "English") -> str:
    """Translate a UI string. Falls back to English, then to the raw key,
    so a missing translation degrades gracefully instead of crashing the
    page -- an unfamiliar key is far more useful to a developer visible in
    the UI than a KeyError."""
    code = LANGUAGE_CODES.get(language, "en")
    entry = _STRINGS.get(key)
    if entry is None:
        return key
    return entry.get(code) or entry.get("en") or key


def available_languages() -> list[str]:
    return list(SUPPORTED_LANGUAGES)


def coverage_report() -> dict[str, list[str]]:
    """Returns, per language code, which keys are MISSING a translation --
    useful in tests and for anyone extending the string table."""
    missing: dict[str, list[str]] = {code: [] for code in LANGUAGE_CODES.values()}
    for key, entry in _STRINGS.items():
        for code in LANGUAGE_CODES.values():
            if not entry.get(code):
                missing[code].append(key)
    return missing
